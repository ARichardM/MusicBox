    private Tr() {}

    public static boolean isSpanish() {
        return "es".equals(Locale.getDefault().getLanguage());
    }

    /** Returns the text in the app language (Spanish source text when the language is Spanish). */
    public static String t(String spanish) {
        if (isSpanish()) return spanish;
        String english = EN.get(spanish);
        return english != null ? english : spanish;
    }

    /** Translates a template and fills it with String.format. */
    public static String f(String spanishTemplate, Object... args) {
        return String.format(Locale.ROOT, t(spanishTemplate), args);
    }

    /** Display name for built-in playlists, whose stored key is always the Spanish name. */
    public static String name(String playlist) {
        return "Favoritos".equals(playlist) ? t("Favoritos") : playlist;
    }
